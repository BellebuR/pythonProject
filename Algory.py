def is_palindrome(s):
    # Шаг 1: Преобразуем строку в нижний регистр для обеспечения нечувствительности к регистру
    s = s.lower()

    # Шаг 2: Удаляем все пробелы и знаки препинания из строки
    s = ''.join(char for char in s if char.isalnum())

    # Шаг 3: Инициализируем два указателя: один в начале строки, другой в конце
    left, right = 0, len(s) - 1

    # Шаг 4: Перебираем строку, пока указатели не встретятся
    while left < right:
        # Шаг 5: Сравниваем символы, на которые указывают указатели
        if s[left] != s[right]:
            # Если они не равны, строка не является палиндромом
            return False
        # Шаг 6: Двигаем левый указатель вправо, а правый указатель влево
        left += 1
        right -= 1

    # Шаг 7: Если все символы совпали, строка является палиндромом
    return True


# Пример использования
print(is_palindrome("A man, a plan, a canal: Panama"))  # Должно вернуть True
print(is_palindrome("race a car"))  # Должно вернуть False